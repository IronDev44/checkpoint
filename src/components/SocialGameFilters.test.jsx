import {render,screen,fireEvent,waitFor,within} from '@testing-library/react';
import FriendPolls from './FriendPolls';
import FriendChallenges from './FriendChallenges';
const games=[{id:'pc',name:'Halo',playedPlatforms:['PC'],platformNames:['PC','Xbox']},{id:'switch',name:'Zelda',platforms:[{name:'Nintendo Switch'}]},{id:'unknown',name:'Mystère'},{id:'removed',name:'Supprimé',_deletedAt:'2026-10-25',playedPlatforms:['PS4']}];
const friends=[{handle:'bob',displayName:'Bob'}];
beforeEach(()=>{jest.spyOn(window,'scrollTo').mockImplementation(()=>{});Object.defineProperty(window,'crypto',{configurable:true,value:{randomUUID:()=> 'test-id'}});});
afterEach(()=>jest.restoreAllMocks());
test('polls keep choices across platform filters, allow removing hidden games and preserve wishlist eligibility',async()=>{
 const request=jest.fn().mockResolvedValue({polls:[]});
 render(<FriendPolls games={[...games,{id:'wish',name:'Envie',status:'wishlist',playedPlatforms:['PS5']}]} friends={friends} request={request}/>);
 await waitFor(()=>expect(screen.queryByText('Chargement des sondages…')).toBeNull());
 fireEvent.click(screen.getByRole('button',{name:'Créer un sondage'}));const form=within(screen.getByRole('dialog'));
 expect(form.queryByRole('checkbox',{name:'Supprimé'})).toBeNull();
 expect(form.getByRole('option',{name:'PS5'})).toBeInTheDocument();
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'PC'}});
 expect(form.queryByRole('checkbox',{name:'Zelda'})).toBeNull();fireEvent.click(form.getByRole('checkbox',{name:'Halo'}));
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'Nintendo Switch'}});
 fireEvent.click(form.getByRole('checkbox',{name:'Zelda'}));
 expect(form.getByRole('region',{name:'Jeux sélectionnés'})).toHaveTextContent('Halo');
 fireEvent.click(form.getByRole('checkbox',{name:/Bob/}));expect(form.getByRole('button',{name:'Lancer le sondage pour 7 jours'})).toBeEnabled();
 fireEvent.click(form.getByRole('button',{name:'Retirer Halo de la sélection'}));
 expect(form.getByRole('button',{name:'Lancer le sondage pour 7 jours'})).toBeDisabled();
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'unknown'}});
 expect(form.getByRole('checkbox',{name:'Mystère'})).toBeVisible();
 fireEvent.change(form.getByLabelText('Rechercher dans mes jeux'),{target:{value:'Halo'}});
 expect(form.queryByRole('checkbox',{name:'Halo'})).toBeNull();expect(form.getByText(/Aucun jeu ne correspond/)).toBeVisible();
});
test('challenges preserve both games and the secret choice across filters but reset the vote when a game is removed',async()=>{
 render(<FriendChallenges games={[...games,{id:'wish',name:'Envie',status:'wishlist',playedPlatforms:['PS5']}]} friends={friends} request={jest.fn().mockResolvedValue({challenges:[]})}/>);
 await waitFor(()=>expect(screen.queryByText('Chargement des défis…')).toBeNull());
 fireEvent.click(screen.getByRole('button',{name:'Créer un défi'}));const form=within(screen.getByRole('dialog'));
 expect(form.queryByRole('option',{name:'PS5'})).toBeNull();expect(form.queryByRole('option',{name:'PS4'})).toBeNull();
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'PC'}});fireEvent.click(form.getByRole('checkbox',{name:'Halo'}));
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'Nintendo Switch'}});fireEvent.click(form.getByRole('checkbox',{name:'Zelda'}));
 fireEvent.click(form.getByRole('radio',{name:'Halo'}));
 fireEvent.change(form.getByLabelText('Plateforme'),{target:{value:'unknown'}});
 expect(form.getByRole('radio',{name:'Halo'})).toBeChecked();expect(form.getByRole('button',{name:'Envoyer le défi pour sept jours'})).toBeEnabled();
 fireEvent.click(form.getByRole('button',{name:'Retirer Halo de la sélection'}));
 expect(form.queryByRole('radio',{name:'Halo'})).toBeNull();expect(form.getByRole('button',{name:'Envoyer le défi pour sept jours'})).toBeDisabled();
 fireEvent.click(form.getByRole('button',{name:'Fermer'}));fireEvent.click(screen.getByRole('button',{name:'Créer un défi'}));
 expect(within(screen.getByRole('dialog')).getByLabelText('Plateforme')).toHaveValue('all');
});
